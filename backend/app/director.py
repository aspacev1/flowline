"""Директор — единственная роль уровня всей установки, а не одной организации.

`Role` (owner/editor/viewer/client в app.models) существует внутри одной
организации, и владельцев организаций в установке может быть сколько угодно.
Директор — другое: конкретный человек, распоряжающийся самой установкой, а не
чьей-то организацией внутри неё. Он один, и адрес закреплён здесь константой,
а не читается из окружения: роль директора не назначают и не переносят на
другой аккаунт правкой .env — она доступна ровно одному адресу, и это
инвариант кода, а не настройка установки.
"""

from app.text import normalize_email

#: Единственный адрес, за которым закреплена роль директора.
DIRECTOR_EMAIL = "alplusvl@gmail.com"

_NORMALIZED_DIRECTOR_EMAIL = normalize_email(DIRECTOR_EMAIL)


def is_director(email: str) -> bool:
    """Носит ли этот адрес роль директора.

    Сравнение — той же нормализацией, что и уникальность аккаунта при
    регистрации (см. app.text.normalize_email): форма письма, под которой
    человек вошёл, не обязана побуквенно совпадать с константой выше.
    """
    return normalize_email(email) == _NORMALIZED_DIRECTOR_EMAIL
