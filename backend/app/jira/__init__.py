"""Интеграция с Jira: подключение, импорт проекта, повторная синхронизация.

Данные текут в одну сторону — из Jira в Planora. Обратная запись (перенос
статусов Planora в Jira) не входит в MVP: план Jira уже ведут в самой Jira,
а Planora здесь читает его, чтобы построить диаграмму Ганта и скоркард,
которых у Jira нет из коробки.

Импорт создаёт новый проект пачкой обычных мутаций с общим `batch_id` — тем
же приёмом, что применение черновика AI (см. app.ai.intake): история задач,
заведённых из Jira, не отличается от истории любых других, и всю пачку можно
отменить одной кнопкой. Синхронизация обновляет уже заведённые строки и
дописывает новые тем же способом.

Модули:
  errors.py     — JiraError, общий для клиента и слоя синхронизации.
  netguard.py   — проверка адреса сайта Jira перед запросом (защита от SSRF).
  client.py     — HTTP поверх Jira Cloud REST API v3 и протокол для тестов.
  credentials.py — хранение подключения (шифрованный токен) и сборка клиента.
  mapping.py    — чистые функции: поле Jira → поле задачи Planora.
  sync.py       — импорт и синхронизация: сборка мутаций из ответа Jira.
"""
