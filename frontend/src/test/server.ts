import { HttpResponse, http } from "msw";
import { setupServer } from "msw/node";

/**
 * Сеть тестов.
 *
 * Начальным обработчиком задан только список организаций: его спрашивает
 * шапка на каждом защищённом экране, и без ответа падал бы любой тест — на
 * запросе, к которому он не имеет никакого отношения. Пустой список означает
 * «переключать не между чем», то есть ровно то состояние, в котором живёт
 * человек с одной организацией. Тест про переключатель перекрывает его через
 * `server.use`, как и любой другой ответ.
 */
export const server = setupServer(http.get("/api/org/list", () => HttpResponse.json([])));
