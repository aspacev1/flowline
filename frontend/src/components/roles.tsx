import { useLocale } from "../i18n/LocaleProvider";

/**
 * Роли, которые можно выдать приглашением. Владельца среди них нет.
 *
 * Владелец распоряжается организацией целиком: удаляет проекты, переутверждает
 * планы, зовёт кого угодно. Выдавать такое выпадающим списком из четырёх слов,
 * где промах на одну строку ничем себя не выдаёт, — слишком дёшево; а
 * приглашение без адреса вдобавок достаётся предъявителю, то есть владельцем
 * становился любой, кто открыл переславшуюся ссылку.
 *
 * Сервер держит то же правило сам (`role_not_invitable` в invitations.py), а не
 * полагается на этот список: спрятанная строка выпадающего списка не мешает
 * отправить запрос руками.
 */
export const INVITABLE_ROLES = ["editor", "viewer", "client"] as const;

/**
 * Роли, которые владелец назначает действующему участнику. Здесь владелец есть.
 *
 * Разница с приглашением не в строгости, а в адресате: приглашение уходит
 * наружу и может достаться предъявителю ссылки, а здесь человек уже внутри,
 * назван поимённо и виден в списке. Это то самое «отдельное действие», ради
 * которого приглашению владельца запрещено.
 */
export const ASSIGNABLE_ROLES = ["owner", "editor", "viewer", "client"] as const;

/**
 * Что эта роль даёт — строкой под выбором.
 *
 * Четыре слова в выпадающем списке не отвечают на единственный вопрос, который
 * задаёт зовущий: «наблюдатель — это кто, и чем он отличается от клиента».
 * Догадка стоит дорого: клиент, позванный наблюдателем, видит все проекты
 * организации, включая те, которые ему показывать не собирались.
 *
 * Пояснение к выбранной роли, а не таблица из четырёх строк: список читают,
 * когда выбирают, и разворачивать под каждым полем справку из четырёх пунктов
 * значит прятать саму форму.
 */
export function RoleHint({ role }: { role: string }) {
  const { t } = useLocale();
  return <p className="muted field__hint">{t(`members.role_about.${role}`)}</p>;
}
