import type { CSSProperties } from "react";

import type { Zoom } from "./scale";

/**
 * Плотность ленты — единственный источник масштаба диаграммы.
 *
 * Здесь лежат все величины, которые обязаны совпасть у разметки, стилей и
 * расчётов: ширина дня, высота строки, высота полоски, высоты шапки. Файл
 * заведён отдельно от `scale.ts` именно ради этого — в нём нет ни дат, ни
 * домена, только геометрия, и его импортирует всякий, кому нужно число, а не
 * правило.
 *
 * Ни одно из этих чисел не повторяется в CSS. Стили берут их через переменные,
 * которые разметка ставит на корне ленты (см. `ganttTokens`): второе такое же
 * число в таблице стилей расходится с первым при первой же правке — а
 * расхождение здесь означает не «чуть иначе выглядит», а стрелки связей мимо
 * полосок и сетку, разъехавшуюся с шапкой к правому краю ленты.
 *
 * Чисто оформительские величины — кегли, скругления, цвета линий — сюда не
 * попадают: их знает только CSS, и место им в `gantt.css` рядом с правилами,
 * которые их применяют.
 */
export const GANTT_DENSITY = {
  /** Ширина календарного дня в пикселях — своя на каждом масштабе. */
  dayWidth: { day: 72, week: 44, month: 22 },
  /** Высота строки: одна на левую колонку, ленту и расчёт стрелок. */
  rowHeight: 50,
  /**
   * Высота обычной полоски задачи. Просвет строки — остаток, по 10 сверху и
   * снизу.
   *
   * Тридцать, а не сорок: полоска в четыре пятых строки читается брусом, и
   * лента из десятка задач превращается в сплошную заливку, по которой не
   * видно самих строк. Две трети — та же пропорция, на которой лента стояла
   * до перехода на эталонный масштаб, и глаз читает её как ряд полосок, а не
   * как закрашенное поле.
   */
  taskHeight: 30,
  /** Сводная полоса категории — тонкая линия по центру строки. */
  summaryHeight: 11,
  /** Полоса месяцев в шапке. */
  monthHeaderHeight: 36,
  /** Полоса дней в шапке: день недели, число и круг сегодняшнего дня. */
  calendarHeaderHeight: 76,
  /** Строка недель — только у относительной шкалы, между месяцами и днями. */
  weekHeaderHeight: 22,
  /** Верхняя панель ленты. */
  toolbarHeight: 56,
  /** Круг вокруг числа сегодняшнего дня в шапке. */
  todayMarkerSize: 32,
  /** Обычная линия сетки. Граница месяца рисуется вдвое толще. */
  gridLineWidth: 1,
} as const;

/**
 * Ширина дня в пикселях для каждого масштаба.
 *
 * `week` — эталонные 44 пикселя: на области около 930 пикселей это ровно три
 * недели. Дневной масштаб крупнее, месячный мельче, и оба целые не случайно:
 * дробная ширина дня разводит сетку — она рисуется от этой величины — и
 * полоски, которые считаются через `xOf`, а расхождение копится к правому краю
 * ленты.
 */
export const DAY_WIDTH: Record<Zoom, number> = GANTT_DENSITY.dayWidth;

/**
 * Высота строки в пикселях.
 *
 * По ней считаются вертикальные координаты стрелок связей (см. Arrows) и по ней
 * же живут строки в CSS — через переменную, которую ставит разметка. Левая
 * колонка и лента здесь одно и то же место в разметке: строка целиком, а не две
 * половины, — так что разойтись им нечем даже при желании.
 */
export const ROW_HEIGHT = GANTT_DENSITY.rowHeight;

/** Высота полоски задачи. */
export const TASK_HEIGHT = GANTT_DENSITY.taskHeight;

/**
 * Переменные масштаба для корня ленты.
 *
 * Разметка ставит их стилем, а CSS читает: так числа выше остаются
 * единственными, и правка ширины дня доходит до сетки, шапки, полосок и
 * стрелок одним движением.
 */
export function ganttTokens(zoom: Zoom): CSSProperties {
  return {
    "--gantt-day-width": `${DAY_WIDTH[zoom]}px`,
    "--gantt-row-height": `${GANTT_DENSITY.rowHeight}px`,
    "--gantt-task-height": `${GANTT_DENSITY.taskHeight}px`,
    "--gantt-summary-height": `${GANTT_DENSITY.summaryHeight}px`,
    "--gantt-month-height": `${GANTT_DENSITY.monthHeaderHeight}px`,
    "--gantt-days-height": `${GANTT_DENSITY.calendarHeaderHeight}px`,
    "--gantt-week-height": `${GANTT_DENSITY.weekHeaderHeight}px`,
    "--gantt-toolbar-height": `${GANTT_DENSITY.toolbarHeight}px`,
    "--gantt-today-size": `${GANTT_DENSITY.todayMarkerSize}px`,
    "--gantt-grid-width": `${GANTT_DENSITY.gridLineWidth}px`,
  } as CSSProperties;
}
