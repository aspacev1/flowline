"""Точка входа Vercel: то же приложение FastAPI, но как serverless-функция.

Vercel ищет функции только в каталоге `api/` в корне проекта, а приложение
живёт в `backend/`. Перенести его сюда нельзя: под docker-compose и в тестах
пакет импортируется как `app.*`, и переезд сломал бы оба сценария ради
третьего. Поэтому здесь только мост — каталог `backend` добавляется в путь
импорта, а сами файлы попадают в функцию через `functions.includeFiles`
в vercel.json: сборщик Python по умолчанию кладёт в функцию только
содержимое `api/`, и без этого импорт ниже упал бы на ModuleNotFoundError.

Маршруты не переопределяются и префикс не навешивается. Rewrite в vercel.json
решает, какая функция обслуживает запрос, но сама функция видит исходный
адрес — тот самый `/api/health`, который уже объявлен в app.main. Если
добавить здесь ещё один `/api`, адреса удвоятся до `/api/api/health`.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))

from app.main import app  # noqa: E402

# Имя `app` — не стилистика: сборщик Python ищет в модуле именно его, чтобы
# опознать ASGI-приложение. Переименование здесь означает 404 на всё API.
__all__ = ["app"]
